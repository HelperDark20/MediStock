// Clave para comparar nombres: minúsculas, sin tildes ni signos, espacios simples
function clave(s) {
  return String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/[^a-z0-9°+]+/g, ' ').trim();
}

